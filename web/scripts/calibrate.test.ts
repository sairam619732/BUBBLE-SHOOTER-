// Offline level calibration: a bot plays every level several times, then shot limits and
// star thresholds are written to src/core/levelCalib.ts. Run with `npm run calibrate`.
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { chooseMove } from '../src/core/bot';
import { LEVEL_COUNT, getLevel, levelParams } from '../src/core/levels';
import { Rng } from '../src/core/rng';
import { SoloGame } from '../src/core/solo';
import { SHOT_LEFT_BONUS } from '../src/core/scoring';

const RUNS = 9;

function pct(sorted: number[], p: number): number {
  return sorted[Math.min(sorted.length - 1, Math.floor(p * (sorted.length - 1) + 0.5))];
}

it('calibrates all levels', () => {
  const out: Record<number, [number, number, number]> = {};
  const lines: string[] = [];
  let failures = 0;
  for (let id = 1; id <= LEVEL_COUNT; id++) {
    const base = getLevel(id);
    const def = { ...base, shots: 999, stars: [0, 0] as [number, number] };
    const shots: number[] = [];
    const scores: number[] = [];
    let lost = 0;
    for (let run = 0; run < RUNS; run++) {
      const g = new SoloGame('level', def, 1000 * id + run);
      const rng = new Rng(77 * id + run);
      while (g.state === 'playing' && g.shotsUsed < 300) {
        const m = chooseMove(g.board, g.queue.cur, g.queue.nxt, { rng, sloppiness: 0.3, aimError: 0.004 });
        if (m.swap) g.swap();
        g.fire(m.angle);
      }
      if (g.state !== 'won') {
        lost++;
        continue;
      }
      shots.push(g.shotsUsed);
      scores.push(g.score - g.endBonus);
    }
    if (lost) failures++;
    shots.sort((a, b) => a - b);
    const t = (id - 1) / (LEVEL_COUNT - 1);
    const slack = 1.5 - 0.32 * t;
    const p80 = shots.length ? pct(shots, 0.8) : 60;
    const limit = Math.ceil(p80 * slack) + 2;
    const finals = shots.map((s, k) => scores[k] + (limit - s) * SHOT_LEFT_BONUS).sort((a, b) => a - b);
    const two = Math.round((finals.length ? pct(finals, 0.35) : 500) / 50) * 50;
    let three = Math.round((finals.length ? pct(finals, 0.8) * 1.05 : 900) / 50) * 50;
    if (three <= two) three = two + 100;
    out[id] = [limit, two, three];
    const p = levelParams(id);
    lines.push(
      `L${String(id).padStart(2)} ${p.shape.padEnd(10)} ${p.scheme.padEnd(8)} colors=${p.nColors} bubbles=${String(base.rows.join('').replace(/[.x]/g, '').length).padStart(3)} ` +
        `shots[min ${shots[0]} med ${pct(shots, 0.5)} max ${shots[shots.length - 1]}] limit=${limit} stars=${two}/${three}${lost ? ` LOST ${lost}/${RUNS}` : ''}`,
    );
  }
  writeFileSync(process.env.CALIB_REPORT || '/tmp/calib-report.txt', lines.join('\n') + `\nfailures: ${failures}\n`);
  console.log(`levels with bot failures: ${failures}`);
  const body = Object.entries(out)
    .map(([k, v]) => `  ${k}: [${v.join(', ')}],`)
    .join('\n');
  writeFileSync(
    new URL('../src/core/levelCalib.ts', import.meta.url),
    `// Generated by \`npm run calibrate\` (scripts/calibrate.test.ts). Do not edit by hand.\n` +
      `// level id -> [shot limit, 2-star score, 3-star score]\n` +
      `export const LEVEL_CALIB: Record<number, [number, number, number]> = {\n${body}\n};\n`,
  );
});
