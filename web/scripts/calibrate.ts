// Offline level calibration: a bot plays every level several times, then shot limits and
// star thresholds are written to src/core/levelCalib.ts.
//
//   npm run calibrate                 all levels, split across CPU cores
//   npm run calibrate -- 61 80        only levels 61..80 (others keep their current values)
import { fork } from 'node:child_process';
import { cpus } from 'node:os';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chooseMove } from '../src/core/bot';
import { LEVEL_CALIB } from '../src/core/levelCalib';
import { LEVEL_COUNT, getLevel, levelParams } from '../src/core/levels';
import { Rng } from '../src/core/rng';
import { SHOT_LEFT_BONUS } from '../src/core/scoring';
import { SoloGame } from '../src/core/solo';

const RUNS = 9;
const MAX_SHOTS = 300;

interface Result {
  id: number;
  calib: [number, number, number];
  line: string;
  lost: number;
}

function pct(sorted: number[], p: number): number {
  return sorted[Math.min(sorted.length - 1, Math.floor(p * (sorted.length - 1) + 0.5))];
}

function calibrate(id: number): Result {
  const base = getLevel(id);
  const def = { ...base, shots: 999, stars: [0, 0] as [number, number] };
  const shots: number[] = [];
  const scores: number[] = [];
  let lost = 0;
  for (let run = 0; run < RUNS; run++) {
    const g = new SoloGame('level', def, 1000 * id + run);
    const rng = new Rng(77 * id + run);
    while (g.state === 'playing' && g.shotsUsed < MAX_SHOTS) {
      const m = chooseMove(g.board, g.queue.cur, g.queue.nxt, { rng, sloppiness: 0.3, aimError: 0.004 });
      if (m.swap) g.swap();
      g.fire(m.angle);
      g.update(0, true); // apply a pending ceiling drop
    }
    if (g.state !== 'won') {
      lost++;
      continue;
    }
    shots.push(g.shotsUsed);
    scores.push(g.score - g.endBonus);
  }
  const order = shots.map((_, k) => k).sort((a, b) => shots[a] - shots[b]);
  const sortedShots = order.map((k) => shots[k]);
  const t = (id - 1) / (LEVEL_COUNT - 1);
  const slack = 1.5 - 0.36 * t;
  const p80 = sortedShots.length ? pct(sortedShots, 0.8) : 60;
  const limit = Math.ceil(p80 * slack) + 2;
  const finals = order.map((k) => scores[k] + (limit - shots[k]) * SHOT_LEFT_BONUS).sort((a, b) => a - b);
  // Stars are tuned for people, not for the bot: 3 stars at the bot's 25th-percentile score
  // (a solid run, not a lucky one) and 2 stars at three quarters of that.
  let three = Math.round((finals.length ? pct(finals, 0.25) : 900) / 50) * 50;
  const two = Math.max(50, Math.round((three * 0.75) / 50) * 50);
  if (three <= two) three = two + 100;
  const p = levelParams(id);
  const bubbles = base.rows.join('').replace(/[.xw]/g, '').length;
  const line =
    `L${String(id).padStart(3)} ${p.shape.padEnd(11)} ${p.scheme.padEnd(8)} c=${p.nColors} press=${String(p.press).padStart(2)} ` +
    `bubbles=${String(bubbles).padStart(3)} shots[min ${sortedShots[0]} med ${pct(sortedShots, 0.5)} max ${sortedShots[sortedShots.length - 1]}] ` +
    `limit=${limit} stars=${two}/${three}${lost ? ` LOST ${lost}/${RUNS}` : ''}`;
  return { id, calib: [limit, two, three], line, lost };
}

const self = fileURLToPath(import.meta.url);
const calibFile = fileURLToPath(new URL('../src/core/levelCalib.ts', import.meta.url));

if (process.argv[2] === '--worker') {
  // Child process: calibrate the given ids and send results back.
  const ids = process.argv.slice(3).map(Number);
  const out: Result[] = ids.map(calibrate);
  process.send!(out, () => process.exit(0));
} else {
  const from = Number(process.argv[2] ?? 1);
  const to = Number(process.argv[3] ?? LEVEL_COUNT);
  const ids: number[] = [];
  for (let id = from; id <= to; id++) ids.push(id);
  // Interleave ids so each worker gets a mix of easy and hard levels.
  const workers = Math.max(1, Math.min(cpus().length, ids.length));
  const chunks: number[][] = Array.from({ length: workers }, () => []);
  ids.forEach((id, k) => chunks[k % workers].push(id));
  const started = Date.now();
  const results: Result[] = [];
  await Promise.all(
    chunks.map(
      (chunk) =>
        new Promise<void>((resolve, reject) => {
          const child = fork(self, ['--worker', ...chunk.map(String)], { execArgv: process.execArgv });
          child.on('message', (m) => results.push(...(m as Result[])));
          child.on('exit', (code) => (code === 0 ? resolve() : reject(new Error(`worker exited ${code}`))));
        }),
    ),
  );
  results.sort((a, b) => a.id - b.id);
  const merged: Record<number, [number, number, number]> = { ...LEVEL_CALIB };
  for (const r of results) merged[r.id] = r.calib;
  const body = Object.keys(merged)
    .map(Number)
    .filter((id) => id <= LEVEL_COUNT)
    .sort((a, b) => a - b)
    .map((id) => `  ${id}: [${merged[id].join(', ')}],`)
    .join('\n');
  writeFileSync(
    calibFile,
    `// Generated by \`npm run calibrate\` (scripts/calibrate.ts). Do not edit by hand.\n` +
      `// level id -> [shot limit, 2-star score, 3-star score]\n` +
      `export const LEVEL_CALIB: Record<number, [number, number, number]> = {\n${body}\n};\n`,
  );
  const failures = results.filter((r) => r.lost);
  const report = results.map((r) => r.line).join('\n') + `\nlevels with bot failures: ${failures.length}\n`;
  if (process.env.CALIB_REPORT) writeFileSync(process.env.CALIB_REPORT, report);
  else console.log(report);
  console.log(`calibrated ${results.length} levels in ${Math.round((Date.now() - started) / 1000)}s; failures: ${failures.map((r) => r.id).join(', ') || 'none'}`);
}
